# -*- coding: utf-8 -*-
"""
Regenerates src/lib/proposal/__fixtures__/parity.json - the reference the TypeScript
projection (src/lib/proposal/project.ts) is checked against.

    python tools/gen_parity.py            (needs numpy and trimesh, see the pipeline requirements.txt)

Source (read only): <BEECHWOOD_PIPELINE_DIR | ../beechwood-pipeline>
    model/out/BEECHWOOD.glb      the meshes of each case
    mangdo/engine                load_glb_meshes + project_view (the reference implementation)

Each case is a small selection of the Beechwood model. For every view the file records the
basis (N, U, V), the projected range and the segment counts project_view returns. The basis is
computed here with the same rules as src/lib/proposal/basis.ts, so the test also pins that port.
"""
import json
import os
import sys

sys.dont_write_bytecode = True   # never write __pycache__ into the pipeline checkout

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
WEB = os.path.dirname(HERE)
PIPE = os.path.abspath(os.environ.get("BEECHWOOD_PIPELINE_DIR") or os.path.join(WEB, "..", "beechwood-pipeline"))
OUT = os.path.join(WEB, "src", "lib", "proposal", "__fixtures__", "parity.json")

sys.path.insert(0, os.path.join(PIPE, "mangdo"))
import engine as gs  # noqa: E402

Y = np.array([0.0, 1.0, 0.0])
Z = np.array([0.0, 0.0, 1.0])


def view_basis(n):
    """Screen axes U (right) and V (down) for the face normal n - the rules of basis.ts."""
    N = np.asarray(n, dtype=float)
    N = N / np.linalg.norm(N)
    if abs(N @ Y) >= np.sqrt(0.5):
        U = Z - N * (Z @ N)
        U = U / np.linalg.norm(U)
        V = np.cross(N, U)
        if V[0] < 0:
            V = -V
    else:
        down = -Y
        V = down - N * (down @ N)
        V = V / np.linalg.norm(V)
        U = np.cross(V, N)
        key = U[2] if abs(U[2]) > 0.1 else U[0]
        if key < 0:
            U = -U
    return U, V, N


# name, mesh names, clip, view normals. The grade normal of the last beam view is the
# slope of span B (a face that is neither vertical nor horizontal).
CASES = [
    ("bw_beam_b2", ["BW_BEAM_B2"], {},
     [(-1, 0, 0), (1, 0, 0), (0, -1, 0), (0, 1, 0), (0.9, -0.3, 0.1)]),
    ("bw_deck_b", ["BW_DECK_B", "BW_RAIL_L", "BW_XF_B"], {"z": [-13.8, 13.8]},
     [(0, 1, 0), (0, -1, 0), (-1, 0, 0), (1, 0, 0)]),
    ("bw_bent_2", ["BW_CAP_B2", "BW_COL_B2_1", "BW_COL_B2_2", "BW_WALL_B2"], {"y": [0.0, 7.5]},
     [(0, 0, -1), (-1, 0, 0), (0, 1, 0)]),
    ("bw_col_b2_1", ["BW_COL_B2_1"], {},
     [(0, 0, -1), (1, 0, 0)]),
]


def main():
    by_name = {name: (V, F) for name, V, F in gs.load_glb_meshes(os.path.join(PIPE, "model", "out", "BEECHWOOD.glb"))}
    cases = []
    for name, picks, clip, normals in CASES:
        meshes = [(m, by_name[m][0], by_name[m][1]) for m in picks]
        clips = [(ax, tuple(r)) for ax, r in clip.items()] or None
        views = []
        for n in normals:
            U, V, N = view_basis(n)
            p = gs.project_view(meshes, U, V, N, clip=clips)
            views.append({
                "N": N.tolist(), "U": U.tolist(), "V": V.tolist(),
                "range": [float(x) for x in p["range"]],
                "counts": {k: len(p[k]) for k in ("sil", "feat", "seg", "hidden")},
            })
        cases.append({
            "name": name, "clip": clip,
            "meshes": [{"name": m, "positions": V.reshape(-1).tolist(), "indices": F.reshape(-1).tolist()}
                       for m, V, F in meshes],
            "views": views,
        })
    doc = {"note": "Generated by tools/gen_parity.py from the pipeline model and sheet engine; do not edit, regenerate instead",
           "cases": cases}
    with open(OUT, "w", encoding="utf-8", newline="\n") as fp:
        json.dump(doc, fp)
        fp.write("\n")
    for c in cases:
        print(c["name"], [v["counts"] for v in c["views"]])
    print("->", os.path.relpath(OUT, WEB).replace("\\", "/"), os.path.getsize(OUT), "bytes")


if __name__ == "__main__":
    main()
